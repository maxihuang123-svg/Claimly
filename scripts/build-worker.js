// Writes worker/generated.js before every `wrangler dev` or `wrangler deploy` (see wrangler.toml).
// A Worker cannot read the source tree at runtime, so what server.js reads from disk is baked in here.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { hash } from '../validation.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (file) => readFileSync(join(root, file), 'utf8');

const engineVersion = hash(['engine.js', 'cases.js', 'validation.js'].map(read));
writeFileSync(join(root, 'worker/generated.js'), `// Generated by scripts/build-worker.js. Do not edit.
export const ENGINE_VERSION = ${JSON.stringify(engineVersion)};
export const EXAMPLES_CSV = ${JSON.stringify(read('test/labelled_development_cases.csv'))};
`);
